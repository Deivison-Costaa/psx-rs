use psx_core::gte::Gte;

// Gabarito de hardware: gte-fuzz (JaCzekanski/ps1-tests, seed 0x00c0ffee), que despeja
// os 64 registradores antes e depois de cada comando rodado em console real. Os valores
// abaixo sao transcricao direta desse log — nao saem da nossa implementacao nem de
// constante derivada a mao da spec (foi exatamente esse tipo de constante que errou 16
// de 64 bytes no MDEC na iteracao 0184).
//
// O log lista o estado ANTES como a SEQUENCIA DE VALORES ESCRITOS em r0..r63, nao como
// o estado final: escrever r15 (SXYP) empurra a FIFO de SXY e escrever r28 (IRGB)
// reescreve IR1..IR3. Por isso `roda` reproduz as escritas em ordem, via write_data/
// write_control, em vez de atribuir os registradores direto.
//
// § GTE Color Calculation Commands (L580-596) de docs/reference/07-gte.md.

fn roda(escritas: &[u32; 64], func: u32) -> Gte {
    let mut gte = Gte::new();
    for (rd, val) in escritas.iter().enumerate().take(32) {
        gte.write_data(rd, *val);
    }
    for (rd, val) in escritas.iter().enumerate().skip(32) {
        gte.write_control(rd - 32, *val);
    }
    gte.execute_command(func);
    gte
}

fn le(gte: &Gte, reg: usize) -> u32 {
    if reg >= 32 {
        gte.read_control(reg - 32)
    } else {
        gte.read_data(reg)
    }
}

fn confere(nome: &str, escritas: &[u32; 64], func: u32, esperado: &[(usize, u32)]) {
    let gte = roda(escritas, func);
    for (reg, alvo) in esperado {
        assert_eq!(
            le(&gte, *reg),
            *alvo,
            "{nome} (func=0x{func:07X}): r{reg} divergiu do gabarito de hardware"
        );
    }
}


