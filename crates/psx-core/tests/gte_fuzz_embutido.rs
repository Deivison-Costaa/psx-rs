fn roda(palavra: u32, entrada: &[u32]) -> [u32; REGS] {
    let mut gte = Gte::new();
    for (i, v) in entrada.iter().enumerate() {
        if i < 32 {
            gte.write_data(i, *v);
        } else {
            gte.write_control(i - 32, *v);
        }
    }
    gte.execute_command(palavra);
    let mut saida = [0u32; REGS];
    for (i, slot) in saida.iter_mut().enumerate() {
        *slot = if i < 32 {
            gte.read_data(i)
        } else {
            gte.read_control(i - 32)
        };
    }
    saida
}

#[test]
fn casos_embutidos_batem_com_o_hardware_em_todos_os_registradores() {
    assert_eq!(CASOS.len(), NOMES.len() * PASSO, "tabela truncada");
    let mut erros = Vec::new();
    for (k, nome) in NOMES.iter().enumerate() {
        let base = k * PASSO;
        let palavra = CASOS[base];
        let medido = roda(palavra, &CASOS[base + 1..base + 1 + REGS]);
        let esperado = &CASOS[base + 1 + REGS..base + PASSO];
        for (i, (m, e)) in medido.iter().zip(esperado.iter()).enumerate() {
            if m != e {
                erros.push(format!(
                    "{nome} ({palavra:#010x}) r[{i}]: esperado {e:#010x}, medido {m:#010x}"
                ));
            }
        }
    }
    assert!(
        erros.is_empty(),
        "{} divergencia(s):\n{}",
        erros.len(),
        erros.join("\n")
    );
}

